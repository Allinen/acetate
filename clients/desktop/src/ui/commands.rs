//! Every commandline's commands, from their declarations (`commandline::schema`): the `?`
//! overlay's Commands tab, and `docs/commands.md` (made by `scripts/gen-commands-doc`, and
//! checked by a test here: a command added to a schema is in both, with nothing written by
//! hand).

use crate::commandline::schema::{Entry, Schema};

/// A commandline: what it's called, where it is, and its declaration.
pub struct Commandline {
    pub title: &'static str,
    pub place: &'static str,
    pub schema: &'static Schema,
}

pub fn all() -> [Commandline; 8] {
    [
        Commandline { title: "Searching and filtering", place: "a list's filter (/), the palette, the phone's search: every key goes with every other, no | needed", schema: &crate::catalog::query::SEARCH },
        Commandline { title: "The command palette", place: "Ctrl+K: the search's keys (above), and these", schema: &super::views::palette::PALETTE_OWN },
        Commandline { title: "The track editor", place: "a track's page in edit mode, Review, Ctrl+E on a list", schema: &acetate_core::editor::parse::EDITOR },
        Commandline { title: "A track's page", place: "the track editor's line on a track's page: these too (listen mode: these alone)", schema: &acetate_core::editor::parse::TRACK_PAGE },
        Commandline { title: "An artist's page", place: "its commandline (/)", schema: &super::views::artist_commands::SCHEMA },
        Commandline { title: "An album's page", place: "its commandline (/)", schema: &super::views::album_commands::SCHEMA },
        Commandline { title: "Credited as…", place: "the popup (Ctrl+B): a command per artist, several apart by |", schema: &super::views::credited_as_line::SCHEMA },
        Commandline { title: "A share link", place: "the popup (Ctrl+Shift+L): the keys go together", schema: &super::share::SHARE },
    ]
}

/// An entry's keys as one line: its forms, then its other names.
pub fn keys(e: &Entry) -> String {
    let indent = "    ".repeat(e.depth);
    match e.aliases.as_slice() {
        [] => format!("{indent}{}", e.forms),
        names => format!("{indent}{}   ({})", e.forms, names.iter().map(|n| format!("{n}:")).collect::<Vec<_>>().join(" ")),
    }
}

/// Whether every command of a commandline is typed by any start of its names (said once).
pub fn all_prefix(entries: &[Entry]) -> bool {
    entries.iter().filter(|e| e.depth == 0).all(|e| e.prefix)
}

/// What an entry is: what it does, its value, and what's worth knowing (`each_prefix`: say
/// it's typed by any start of its names, if it is).
pub fn what(e: &Entry, each_prefix: bool) -> String {
    let mut out = e.help.to_string();
    if e.value != "nothing" && e.value != "text" {
        out.push_str(&format!(" · {}", e.value));
    }
    if !e.note.is_empty() {
        out.push_str(&format!(" · {}", e.note));
    }
    if each_prefix && e.prefix {
        out.push_str(" · any start of its names");
    }
    out
}

/// `docs/commands.md` (written by the test below).
#[cfg(test)]
pub fn markdown() -> String {
    let cell = |s: &str| s.replace('|', "\\|");
    let mut out = vec![
        "# Commands".to_string(),
        String::new(),
        "<!-- Generated by scripts/gen-commands-doc from the commandlines' declarations: edit those, not this. -->".to_string(),
        String::new(),
        "Every commandline, as the app declares it. In the app, `?` (or `F1`), then the Commands tab, lists".to_string(),
        "the same. The language is the same everywhere: `key:value`, `|` between commands, a command's".to_string(),
        "arguments after it in any order, `-key:value` to take one off and `-key` to clear (where a".to_string(),
        "command has them), `\"…\"` or `\\|` for a value with a `|` in it. Places: the value is what, `n:` is".to_string(),
        "where (`cover:3 n:1`).".to_string(),
        String::new(),
        "The graphs show what can follow what; the tables say what each key takes.".to_string(),
        String::new(),
    ];
    for c in all() {
        out.push(format!("## {}", c.title));
        out.push(String::new());
        let entries = c.schema.entries();
        let prefix = all_prefix(&entries);
        out.push(format!("{}.{}", capitalized(c.place), if prefix { " A key can be typed by any start of its names (two letters at least)." } else { "" }));
        out.push(String::new());
        if let Some(graph) = c.schema.graph() {
            out.push("```mermaid".into());
            out.push(graph);
            out.push("```".into());
            out.push(String::new());
        }
        out.push("| Key | Other names | Takes | What it does |".into());
        out.push("|---|---|---|---|".into());
        for e in entries {
            let arrow = if e.depth > 0 { format!("{}↳ ", "&nbsp;&nbsp;".repeat(e.depth)) } else { String::new() };
            let forms = e.forms.split("  ").map(|f| format!("`{}`", cell(f))).collect::<Vec<_>>().join(" ");
            let names = e.aliases.iter().map(|n| format!("`{n}:`")).collect::<Vec<_>>().join(" ");
            let mut notes: Vec<String> = (!e.note.is_empty()).then(|| e.note.clone()).into_iter().collect();
            if e.prefix && !prefix {
                notes.push("any start of its names".into());
            }
            let mut what = cell(e.help);
            if !notes.is_empty() {
                what.push_str(&format!(" ({})", cell(&notes.join("; "))));
            }
            out.push(format!("| {arrow}{forms} | {names} | {} | {what} |", cell(&e.value)));
        }
        out.push(String::new());
    }
    out.join("\n")
}

#[cfg(test)]
fn capitalized(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

#[cfg(test)]
mod tests {
    /// `docs/commands.md` is what the declarations say. `ACETATE_WRITE_DOCS=1` writes it
    /// (`scripts/gen-commands-doc`).
    #[test]
    fn commands_doc_is_up_to_date() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/commands.md");
        let made = super::markdown();
        if std::env::var_os("ACETATE_WRITE_DOCS").is_some() {
            std::fs::write(&path, &made).unwrap();
            return;
        }
        let there = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(there == made, "docs/commands.md is out of date: run scripts/gen-commands-doc");
    }
}
