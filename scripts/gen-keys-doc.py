#!/usr/bin/env python3
"""Writes docs/keys.md from the table behind the app's `?` overlay
(clients/desktop/src/ui/keymap.rs), so the two never drift apart.

    scripts/gen-keys-doc.py           # writes it
    scripts/gen-keys-doc.py --check   # says whether it is up to date (the hooks and CI)
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / "clients/desktop/src/ui/keymap.rs").read_text()
table = source.split("pub const GROUPS", 1)[1].split("/// Draws the overlay", 1)[0]

def unescape(text):
    return text.replace('\\"', '"').replace("\\\\", "\\")

out = [
    "# Keys",
    "",
    "<!-- Generated by scripts/gen-keys-doc.py from the desktop app's keymap.rs: edit that, not this. -->",
    "",
    "Press `?` or `F1` in the app for this list. Keys work outside text fields; punctuation is",
    "matched by the character you type, so it works on non-US layouts. What the commandlines",
    "take (`artist:`, `cover:`, `go:`…) is in [Commands](commands.md) (the overlay's other tab).",
    "",
]
group = re.compile(r'\(\s*"((?:[^"\\]|\\.)*)",\s*&\[(.*?)\],\s*\),', re.S)
binding = re.compile(r'\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)')
for title, body in group.findall(table):
    out += [f"## {unescape(title)}", "", "| Keys | Does |", "|---|---|"]
    for keys, what in binding.findall(body):
        cell = lambda s: "`" + unescape(s).replace("|", "\\|") + "`"
        out.append(f"| {cell(keys)} | {unescape(what).replace('|', '\\|')} |")
    out.append("")
text = "\n".join(out)
target = root / "docs/keys.md"
if "--check" in sys.argv:
    if target.read_text() != text:
        sys.exit("docs/keys.md is out of date: run scripts/gen-keys-doc.py")
else:
    target.write_text(text)
